#!/usr/bin/env python3
"""
Generate the OTA firmware SIGNING KEYPAIR (ECDSA, NIST P-256 / secp256r1).

Run this ONCE. It creates:
  * a PRIVATE key, written OUTSIDE the repo (default ~/.abrp-ota/ota_private_key.pem, mode 0600).
    This key is the entire trust root of the update system - anything signed with it will be accepted by every
    dongle carrying the matching public key. Back it up somewhere safe and offline. Never commit it. If it
    leaks, an attacker can install arbitrary firmware on your dongles; if you lose it, you can no longer ship
    updates to already-deployed dongles (they only trust the public key baked into their current firmware).
  * the matching PUBLIC key, written into baseLogger/Helpers/ota_pubkey.h (safe to commit - it can only
    VERIFY signatures, never create them).

No Python packages required - uses the openssl CLI.

Usage:
    python3 tools/ota_keygen.py                 # generate (refuses to clobber an existing private key)
    python3 tools/ota_keygen.py --force         # regenerate, INVALIDATING every already-deployed dongle
    python3 tools/ota_keygen.py --key <path>    # use a different private-key location
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PUBKEY_HEADER = HERE.parent / "Helpers" / "ota_pubkey.h"
DEFAULT_KEY = Path.home() / ".abrp-ota" / "ota_private_key.pem"


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, **kw)


def public_point_from_key(key_path: Path) -> bytes:
    """Extract the 65-byte uncompressed EC point (0x04||X||Y) from a P-256 private key."""
    # The DER SubjectPublicKeyInfo for P-256 is 91 bytes and ends with the 65-byte uncompressed point.
    der = run(["openssl", "ec", "-in", str(key_path), "-pubout", "-outform", "DER"]).stdout
    point = der[-65:]
    if len(point) != 65 or point[0] != 0x04:
        sys.exit(f"ERROR: unexpected public key encoding (got {len(der)} DER bytes, "
                 f"point starts 0x{point[0]:02x}, expected 0x04)")
    return point


def write_pubkey_header(point: bytes, key_path: Path):
    rows = []
    for i in range(0, len(point), 16):
        rows.append("  " + " ".join(f"0x{b:02x}," for b in point[i:i + 16]))
    body = "\n".join(rows).rstrip(",")
    # ~-relative, so regenerating doesn't commit the developer's home directory into the header.
    try:
        shown_path = "~/" + str(key_path.resolve().relative_to(Path.home().resolve()))
    except ValueError:
        shown_path = str(key_path)

    PUBKEY_HEADER.write_text(f'''#pragma once
/*
  OTA signing PUBLIC key (ECDSA, NIST P-256 / secp256r1).

  GENERATED by tools/ota_keygen.py - do not edit by hand.
  Private key: {shown_path}   (NEVER commit it; back it up offline)

  Only the PUBLIC key lives here, so this file is safe to commit: it can verify signatures but cannot create
  them. It is compiled into the firmware, which is what makes signature verification the trust boundary - the
  distribution channel (GitHub, the phone, the BLE link) does not need to be trusted.

  Format: the uncompressed EC point, 65 bytes = 0x04 || X(32) || Y(32).
*/

#define OTA_PUBKEY_LEN 65

static const uint8_t OTA_PUBKEY[OTA_PUBKEY_LEN] = {{
{body}
}};
''')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--key", type=Path, default=DEFAULT_KEY, help="private key path")
    ap.add_argument("--force", action="store_true", help="overwrite an existing private key")
    args = ap.parse_args()

    if args.key.exists() and not args.force:
        sys.exit(
            f"ERROR: {args.key} already exists.\n"
            "Refusing to overwrite your signing key. Generating a NEW key would make every dongle already\n"
            "running firmware built with the OLD public key reject all future updates (they would have to be\n"
            "re-flashed over USB). Pass --force only if you are certain."
        )

    args.key.parent.mkdir(parents=True, exist_ok=True)
    run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", str(args.key)])
    os.chmod(args.key, 0o600)

    point = public_point_from_key(args.key)
    write_pubkey_header(point, args.key)

    print(f"Private key : {args.key}  (mode 0600 - BACK THIS UP OFFLINE, never commit)")
    print(f"Public key  : {PUBKEY_HEADER}  (safe to commit)")
    print(f"Point       : {point.hex()}")
    print("\nNext: rebuild and flash the dongle OVER USB once, so it carries this public key.")
    print("      Only then can it accept signed OTA updates (tools/ota_sign.py).")


if __name__ == "__main__":
    main()
