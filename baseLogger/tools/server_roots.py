#!/usr/bin/env python3
"""
Write baseLogger/Helpers/server_roots.h: the root CAs the cellular modem verifies the upload server
against, as one DER PKCS#7 for AT+CSSLCFG="CONVERT". Rule and measured modem limits: DONGLE_CONTEXT.md §6a.

Roots only - a leaf or an intermediate is refused, because those rotate and trusting one would break
uploads on the next rotation. MAX_BYTES is the modem's CONVERT limit (5120 accepted, 5121 refused).

Usage, from baseLogger/:
    python3 tools/server_roots.py AmazonRootCA1.pem AmazonRootCA3.pem ...

Needs the openssl CLI (OpenSSL or LibreSSL).
"""

import argparse
import datetime
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "Helpers" / "server_roots.h"
MAX_BYTES = 5120
OID_SIGNED_DATA = bytes.fromhex("2a864886f70d010702")  # 1.2.840.113549.1.7.2
OID_DATA = bytes.fromhex("2a864886f70d010701")         # 1.2.840.113549.1.7.1


def openssl(*args, data=None):
    return subprocess.run(["openssl", *args], input=data, capture_output=True, check=True).stdout


def field(pem, flag):
    return openssl("x509", "-noout", flag, "-nameopt", "RFC2253", data=pem).decode().split("=", 1)[1].strip()


def not_after_of(pem):
    text = openssl("x509", "-noout", "-enddate", data=pem).decode().split("=", 1)[1].strip()
    return datetime.datetime.strptime(text, "%b %d %H:%M:%S %Y %Z").replace(tzinfo=datetime.timezone.utc)


def fingerprint(pem):
    return openssl("x509", "-noout", "-fingerprint", "-sha256", data=pem).decode().split("=", 1)[1].strip().replace(":", "")


def describe(pem):
    """(common name, notAfter date, SHA-256 fingerprint) of one PEM certificate; raises unless it is a root CA."""
    subject = field(pem, "-subject")
    if subject != field(pem, "-issuer") or "CA:TRUE" not in openssl("x509", "-noout", "-text", data=pem).decode():
        raise ValueError(f"not a self-signed root CA: {subject}")
    with tempfile.TemporaryDirectory() as empty, tempfile.NamedTemporaryFile(suffix=".pem") as f:
        f.write(pem)
        f.flush()
        openssl("verify", "-CApath", empty, "-CAfile", f.name, f.name)  # its signature verifies against itself
    cn = next(p.split("=", 1)[1] for p in subject.split(",") if p.startswith("CN="))
    return cn, not_after_of(pem).date().isoformat(), fingerprint(pem)


def tlv(tag, body):
    n = len(body)
    length = bytes([n]) if n < 0x80 else bytes([0x80 | ((n.bit_length() + 7) // 8)]) + n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([tag]) + length + body


def pkcs7(pems):
    """Certificates-only PKCS#7 SignedData, assembled here so the bytes do not depend on the openssl flavour.
    The layout (empty crls [1] included) is LibreSSL crl2pkcs7's, the one tested on the modem."""
    certs = b"".join(openssl("x509", "-outform", "DER", data=p) for p in pems)
    signed_data = tlv(0x30, tlv(0x02, b"\x01") + tlv(0x31, b"") + tlv(0x30, tlv(0x06, OID_DATA)) +
                      tlv(0xa0, certs) + tlv(0xa1, b"") + tlv(0x31, b""))
    return tlv(0x30, tlv(0x06, OID_SIGNED_DATA) + tlv(0xa0, signed_data))


def render(pems):
    rows = [describe(p) for p in pems]
    der = pkcs7(pems)
    if len(der) > MAX_BYTES:
        raise ValueError(f"bundle is {len(der)} bytes; the modem's CONVERT accepts at most {MAX_BYTES}")
    table = "".join(f"    {cn:<52} until {end}\n      {fp}\n" for cn, end, fp in rows)
    body = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in der[i:i + 16]) for i in range(0, len(der), 16))
    return f"""#pragma once
/*
  Root CAs the cellular modem verifies the upload server against, as one DER PKCS#7. Data only;
  #included into logger.ino like the other helpers. Why these roots and the modem's limits:
  DONGLE_CONTEXT.md §6a.

  GENERATED by tools/server_roots.py - do not edit by hand. tests/run_server_roots_checks.py checks it.

{table}*/

#define SERVER_ROOTS_LEN {len(der)}

static const uint8_t SERVER_ROOTS_P7B[SERVER_ROOTS_LEN] = {{
{body}
}};
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("pems", nargs="+", type=Path)
    pems = []
    for path in parser.parse_args().pems:
        data = path.read_bytes()
        if data.count(b"-----BEGIN CERTIFICATE-----") != 1:
            sys.exit(f"{path}: expected exactly one PEM certificate")
        pems.append(data)
    try:
        HEADER.write_text(render(pems))
    except (ValueError, subprocess.CalledProcessError) as e:
        sys.exit(f"refused: {e}")
    print(f"wrote {HEADER}")


if __name__ == "__main__":
    main()
